// Vendor the shared element library (qant-au/elements) into the catalogue.
//
//   node scripts/sync-elements.mjs [path-to-elements-checkout]
//
// Copies dist/manifest.json, dist/models.json and dist/plan/*.svg into
// src/res/catalog/elements/
// and records the source commit. Defaults to ../elements next to this repo.
// Run `npm run build` in the elements checkout first.
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const source = resolve(process.argv[2] ?? resolve(root, '../elements'));
const dist = resolve(source, 'dist');
const target = resolve(root, 'src/res/catalog/elements');

if (!existsSync(resolve(dist, 'manifest.json'))) {
  console.error(`No ${dist}/manifest.json. Run \`npm run build\` in ${source}.`);
  process.exit(1);
}

const commit = execFileSync('git', ['-C', source, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
const dirty = execFileSync('git', ['-C', source, 'status', '--porcelain'], { encoding: 'utf8' }).trim() !== '';

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(resolve(dist, 'manifest.json'), resolve(target, 'manifest.json'));
cpSync(resolve(dist, 'models.json'), resolve(target, 'models.json'));
cpSync(resolve(dist, 'plan'), resolve(target, 'plan'), { recursive: true });
writeFileSync(
  resolve(target, 'SOURCE.md'),
  `# Vendored element library\n\nGenerated by [qant-au/elements](https://github.com/qant-au/elements) at \`${commit}\`${dirty ? ' (with uncommitted changes)' : ''}.\nDo not edit these files: change the element in that repo and re-run\n\`node scripts/sync-elements.mjs\`.\n`
);
console.log(`Synced elements @ ${commit}${dirty ? '+dirty' : ''} → src/res/catalog/elements/`);
