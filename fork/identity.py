#!/usr/bin/env python3
"""Give the upstream tree Axonometra's identity, so it installs beside NeonPlan 3D.

Axonometra is a maintained fork of NeonPlan 3D (https://github.com/Mastershort/neonplan3d).
The rename is a transform, not a hand edit: it is applied to upstream's tree as a whole,
and re-applied after every upstream merge (fork/MERGING.md), so the same input always
gives the same output and a merge never has to re-do it by hand.

What changes:
  - the product name: NeonPlan 3D / NeonPlan -> Axonometra, in code, UI strings and docs
  - the Home Assistant identity: integration domain and folder, websocket commands,
    services, storage keys, static path, panel and card element names, card type
  - the custom elements, window events and localStorage keys that would collide with an
    upstream install on the same page (fp3d-<element> -> axonometra-<element>)
  - the manifest's owner, documentation and issue tracker; the integration's brand icons
  - upstream files the fork does not carry are removed (DELETE)

What deliberately does not:
  - LICENSE (the author's MIT text and copyright line), NOTICE, our README and CLAUDE.md,
    upstream's CHANGELOG.md and docs/release-*.md (his release history)
  - every address on the author's hosts (mastershort.de, github.com/mastershort/...)
  - the pack fingerprint prefix `neonplan3d:` and the `.fp3dpack` extension, so the
    author's signed furniture packs keep working
  - the file-format markers (`"neonplan3d"` plan export, `neonplan3d-backup`,
    `neonplan-import`), so plans and backups move both ways between the two
  - internal CSS classes and custom properties (`fp3d-*`), which live inside each
    element's shadow root and cannot collide; renaming them would only make merges worse
  - built output (custom_components/axonometra/frontend/*.js, site/import/*.js): it is
    regenerated by the build, never transformed

Usage:  python3 fork/identity.py           apply (idempotent), then:
          ruff format custom_components tests && (cd frontend && npm run build)
        python3 fork/identity.py --check   exit 1 if anything would change
"""
from __future__ import annotations

import re
import shutil
import subprocess
import sys
from fnmatch import fnmatch
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FORK = ROOT / "fork"

# Never transformed: ours, the author's licence, his release history, built output.
EXCLUDE = [
    "LICENSE", "NOTICE", "README.md", "CLAUDE.md", "CHANGELOG.md", "docs/release-*.md",
    "fork/*", "custom_components/*/frontend/*.js", "site/import/*.js",
    # ours, and they name the upstream product on purpose
    "custom_components/axonometra/upstream.py", "frontend/src/upstream.ts",
]
# Upstream files the fork does not carry: his product roadmap, his shop's server code,
# his donation link, and the workflows that post to his Discord, probe his shop, publish his
# site and check his HACS releases download (Axonometra publishes none yet; see fork/README.md
# for the repo decisions).
DELETE = [
    "ROADMAP.md", "tools/shop/*", ".github/FUNDING.yml",
    ".github/workflows/discord-release.yml", ".github/workflows/shop-check.yml",
    ".github/workflows/pages.yml", ".github/workflows/hacs-check.yml", "tools/hacs_download_check.py",
]
BUILT = "custom_components/*/frontend/*.js"

NAMES = [
    ("NeonPlan 3D", "Axonometra"), ("NeonPlan-3D", "Axonometra"), ("NeonPlan3D", "Axonometra"),
    ("NeonPlan", "Axonometra"), ("NEONPLAN3D", "AXONOMETRA"), ("NEONPLAN", "AXONOMETRA"),
    ("neonplan3d", "axonometra"), ("neonplan", "axonometra"),
]
# Custom elements, window events and the tooltip localStorage prefix that an upstream
# install on the same page would also define.
ELEMENTS = re.compile(
    r"\bfp3d-(?:(view3d|time-bar|room-panel|quick-menu|mic-probe|library|extensions|"
    r"entity-picker|editor|replay-blocked)\b|(tt-))"
)

# Spans that keep upstream's spelling: addresses on the author's own hosts, then the
# markers below. (Pack ids such as `mastershort.living` are not hosts and are not touched.)
AUTHOR_URL = re.compile(
    r"(?:https?://)?(?:[\w-]+\.)*mastershort\.(?:de|com)\b[\w./%#?=&:~+-]*"
    r"|(?:https?://)?(?:raw\.githubusercontent|github)\.com/mastershort/[\w./%#?=&:~+-]*",
    re.IGNORECASE,
)
PROTECT = [
    re.compile(r"neonplan3d:\{"),                 # pack fingerprint: sha256("neonplan3d:" + id)
    re.compile(r'"neonplan3d:"'),
    re.compile(r"neonplan3d-backup"),             # backup file format
    re.compile(r"neonplan-import"),               # import file format and its page
    re.compile(r'EXPORT_FORMAT = "neonplan3d"'),  # plan export format
    re.compile(r'format: "neonplan3d"'),
    re.compile(r"src=neonplan-app"),              # the shop's referral tag, for when it is switched on
]

# Exact edits made after the transform, per file: (old, new).
OVERRIDES = {
    "custom_components/axonometra/manifest.json": [
        ('"codeowners": ["@Mastershort"]', '"codeowners": ["@qant-au"]'),
        ('"documentation": "https://mastershort.de/en/neonplan3d/manual/"',
         '"documentation": "https://github.com/qant-au/axonometra"'),
        ('"issue_tracker": "https://github.com/mastershort/neonplan3d/issues"',
         '"issue_tracker": "https://github.com/qant-au/axonometra/issues"'),
    ],
    # The editor's help box: problems and ideas come to this repo; there is no Axonometra Discord.
    "frontend/src/components/editor.ts": [
        ("https://github.com/Mastershort/neonplan3d/issues/new/choose", "https://github.com/qant-au/axonometra/issues/new/choose"),
        ("https://github.com/Mastershort/neonplan3d/discussions/categories/ideas", "https://github.com/qant-au/axonometra/discussions"),
        ('        <a class="fp3d-btn" href="https://discord.gg/SSdVVFsev7" target="_blank" rel="noopener">💬 ${this.t("help_discord")}</a>\n', ""),
    ],
    # Upstream's guard reads the public texts, ROADMAP.md among them; the fork drops that file.
    "frontend/src/unreleased-guard.test.ts": [
        ('"CHANGELOG.md", "ROADMAP.md", ', '"CHANGELOG.md", '),
    ],
}
# Our files copied over upstream's.
COPIES = {
    "brand/icon.png": "custom_components/axonometra/brand/icon.png",
    "brand/icon@2x.png": "custom_components/axonometra/brand/icon@2x.png",
    # The issue chooser points at this repo, not at the author's Discord, discussions and shop.
    "github/ISSUE_TEMPLATE/config.yml": ".github/ISSUE_TEMPLATE/config.yml",
}


def tracked() -> list[str]:
    out = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, check=True).stdout
    return [p for p in out.decode().split("\0") if p]


def matches(path: str, patterns: list[str]) -> bool:
    return any(fnmatch(path, pat) for pat in patterns)


def rename_path(path: str) -> str:
    if "neonplan-import" in path:
        return path
    for old, new in NAMES:
        path = path.replace(old, new)
    return path


def transform(text: str) -> str:
    kept: list[str] = []

    def hold(m: re.Match) -> str:
        kept.append(m.group(0))
        return f"\x00{len(kept) - 1}\x00"

    for pat in [AUTHOR_URL, *PROTECT]:
        text = pat.sub(hold, text)
    for old, new in NAMES:
        text = text.replace(old, new)
    text = ELEMENTS.sub(lambda m: "axonometra-" + (m.group(1) or m.group(2)), text)
    return re.sub(r"\x00(\d+)\x00", lambda m: kept[int(m.group(1))], text)


def main() -> int:
    check = "--check" in sys.argv[1:]
    changed: list[str] = []

    def git_rm(path: str, why: str) -> None:
        changed.append(f"delete {path}{why}")
        if not check:
            subprocess.run(["git", "rm", "-qf", path], cwd=ROOT, check=True)

    for path in tracked():
        if matches(path, DELETE):
            git_rm(path, "")
            continue
        # Built bundles are regenerated, never transformed: one left at a renamed path is stale.
        if fnmatch(path, BUILT) and rename_path(path) != path:
            git_rm(path, " (stale build output)")
            continue
        if matches(path, EXCLUDE) or not (ROOT / path).is_file():
            continue
        new_path = rename_path(path)
        if new_path != path:
            changed.append(f"move {path} -> {new_path}")
            if not check:
                (ROOT / new_path).parent.mkdir(parents=True, exist_ok=True)
                subprocess.run(["git", "mv", path, new_path], cwd=ROOT, check=True)
        target = ROOT / (path if check else new_path)
        raw = target.read_bytes()
        if b"\0" in raw:
            continue
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            continue
        new = transform(text)
        if new != text:
            changed.append(f"edit {new_path}")
            if not check:
                target.write_text(new, encoding="utf-8")

    for path, edits in OVERRIDES.items():
        target = ROOT / path
        if not target.exists():
            continue
        text = target.read_text(encoding="utf-8")
        new = text
        for old, rep in edits:
            new = new.replace(old, rep)
        if new != text:
            changed.append(f"override {path}")
            if not check:
                target.write_text(new, encoding="utf-8")

    for src, dest in COPIES.items():
        s, d = FORK / src, ROOT / dest
        if d.parent.is_dir() and (not d.exists() or d.read_bytes() != s.read_bytes()):
            changed.append(f"copy {dest}")
            if not check:
                shutil.copyfile(s, d)

    for line in changed:
        print(line)
    if check:
        print(f"{len(changed)} change(s) pending" if changed else "identity: clean")
        return 1 if changed else 0
    print(f"{len(changed)} change(s) applied; now run: ruff format custom_components tests"
          " && (cd frontend && npm run build)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
